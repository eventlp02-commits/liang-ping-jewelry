async function render(id) {
  const { source, crop: [left, top, width, height], paths } = pieces[id];
  const photograph = await sharp(fileURLToPath(new URL(source, site)))
    .extract({ left, top, width, height }).removeAlpha().raw().toBuffer();
  // Supersample only the coverage, never resample or redraw the source pixels.
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${width * 4}"
    height="${height * 4}" viewBox="0 0 ${width} ${height}">
    <rect width="100%" height="100%" fill="black"/>
    ${paths.map(d => `<path d="${d}" fill="white" fill-rule="evenodd"/>`).join("")}
    </svg>`;
  const mask = await sharp(Buffer.from(svg)).resize(width, height, { kernel: "lanczos2" })
    .removeAlpha().greyscale().raw().toBuffer();
  const rgba = Buffer.alloc(width * height * 4);
  let x0 = width, x1 = -1, y0 = height, y1 = -1;
  for (let i = 0; i < mask.length; i++) {
    const a = mask[i];
    if (!a) continue;
    const x = i % width, y = Math.floor(i / width);
    x0 = Math.min(x0, x); x1 = Math.max(x1, x);
    y0 = Math.min(y0, y); y1 = Math.max(y1, y);
    rgba[i*4] = photograph[i*3]; rgba[i*4+1] = photograph[i*3+1];
    rgba[i*4+2] = photograph[i*3+2]; rgba[i*4+3] = a;
  }
  if (x1 < 0 || x0 < 2 || y0 < 2 || x1 > width - 3 || y1 > height - 3) {
    throw new Error(`${id}: empty mask or clipped silhouette`);
  }
  const bounds = { left: x0 - 2, top: y0 - 2, width: x1 - x0 + 5, height: y1 - y0 + 5 };
  const image = await sharp(rgba, { raw: { width, height, channels: 4 } })
    .extract(bounds)
    .webp({ lossless: true, effort: 6 }).toBuffer();
  await writeFile(new URL(`${id}.webp`, out), image);
  return [left + bounds.left, top + bounds.top, bounds.width, bounds.height];
}

const ids = process.argv.length > 2 ? process.argv.slice(2) : Object.keys(pieces);
if (ids.some(id => !Object.hasOwn(pieces, id))) {
  throw new Error(`Choose from: ${Object.keys(pieces).join(", ")}`);
}
await mkdir(out, { recursive: true });
const rendered = new Map();
for (const id of new Set(ids)) rendered.set(id, await render(id));
const order = Object.keys(pieces);
if (order.every(id => rendered.has(id))) {
  const lines = order.map(id => `  "${id}": ${JSON.stringify(rendered.get(id))}`);
  await writeFile(registrations, `{\n${lines.join(",\n")}\n}\n`);
}
