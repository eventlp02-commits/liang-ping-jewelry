function pearl([l, t, r, b]) {
  const w = r - l, h = b - t;
  return `M${l + .49*w} ${t}
    C${l + .82*w} ${t - .3} ${r - .1} ${t + .21*h} ${r} ${t + .49*h}
    C${r + .4} ${t + .77*h} ${l + .8*w} ${b - .4} ${l + .52*w} ${b}
    C${l + .23*w} ${b + .2} ${l + .4} ${t + .82*h} ${l} ${t + .54*h}
    C${l - .4} ${t + .27*h} ${l + .15*w} ${t + .02*h} ${l + .49*w} ${t} Z`;
}

