import assert from "node:assert/strict";
import { chromium } from "playwright-core";
import { mkdir } from "node:fs/promises";
import { resolve } from "node:path";
import { pieces } from "../src/components/sites/onde/content.mjs";

const url=process.env.PREVIEW_URL ?? "http://127.0.0.1:3197/";
const browser=await chromium.launch({channel:"chrome",headless:true,args:["--enable-unsafe-swiftshader"]});
const errors=[];
const proof=resolve(process.env.PROOF_DIR??"../quiet-proof");
await mkdir(proof,{recursive:true});
const settle=page=>page.waitForFunction(()=>!document.documentElement.dataset.flight);
try{
  const page=await browser.newPage({viewport:{width:1440,height:900}});
  page.on("pageerror",e=>errors.push(e.message));
  await page.goto(`${url}#chapter-2`);
  assert.equal(await page.locator(".wordmark").innerText(),"Liang Ping");
  assert.equal(await page.getByRole("heading",{name:"探索作品"}).count(),1);
  assert.equal(await page.getByRole("button",{name:"播放音乐"}).count(),1);
  assert.equal(await page.evaluate(()=>document.querySelector("audio").paused),true);
  await page.getByRole("button",{name:"探索作品",exact:true}).click();
  await page.waitForURL(/#signal$/);await settle(page);
  await page.waitForFunction(()=>document.querySelector("audio").currentTime>.2);
  const before=await page.evaluate(()=>({time:document.querySelector("audio").currentTime,src:document.querySelector("audio").currentSrc}));
  assert.ok(before.src.includes("someone-in-the-crowd")||before.src.startsWith("data:audio/"));
  await page.getByRole("button",{name:"下一件作品",exact:true}).click();
  await page.waitForURL(/#pulse$/);await settle(page);
  assert.ok(await page.evaluate(time=>document.querySelector("audio").currentTime>time,before.time),"music must continue between objects");
  await page.getByRole("button",{name:"暂停音乐"}).click();
  assert.equal(await page.evaluate(()=>document.querySelector("audio").paused),true);
  const paused=await page.evaluate(()=>document.querySelector("audio").currentTime);
  await page.getByRole("button",{name:"上一件作品",exact:true}).click();
  await page.waitForURL(/#signal$/);await settle(page);
  assert.equal(await page.evaluate(()=>document.querySelector("audio").paused),true,"navigation must respect an explicit pause");
  assert.ok(Math.abs(await page.evaluate(()=>document.querySelector("audio").currentTime)-paused)<.05);
  const text=await page.locator("body").innerText();
  for(const piece of pieces){assert.ok(!text.includes(piece.description));assert.ok(!text.includes(piece.detail));}
  assert.ok(!text.includes("Atelier Onde"));
  await page.waitForSelector("[data-printed]");
  const range=page.getByRole("slider",{name:"观看进度"});
  await range.focus();await page.keyboard.press("End");
  await page.waitForFunction(()=>Number(document.querySelector("[data-material-stage]").dataset.phase)===2);
  await page.keyboard.press("Home");
  await page.waitForFunction(()=>scrollY<10);
  await page.getByRole("button",{name:"查看原图"}).click();
  await page.getByRole("dialog",{name:"作品原图"}).waitFor();
  await page.getByRole("button",{name:"放大"}).click();
  await page.waitForFunction(()=>document.querySelector(".detail-viewer").dataset.zoomed==="true");
  assert.equal(await page.locator(".detail-viewer").getAttribute("data-zoomed"),"true");
  for(let i=0;i<2;i++)await page.getByRole("button",{name:"放大"}).click();
  await page.waitForFunction(()=>document.querySelector(".viewer-tools span").textContent==="400%");
  await page.mouse.move(720,450);await page.mouse.down();await page.mouse.move(1400,450,{steps:10});await page.mouse.up();
  assert.equal(await page.evaluate(()=>{
    const photo=document.querySelector(".viewer-canvas img").getBoundingClientRect();
    const frame=document.querySelector(".viewer-frame").getBoundingClientRect();
    return photo.left<=frame.left+1&&photo.right>=frame.right-1&&photo.top<=frame.top+1&&photo.bottom>=frame.bottom-1;
  }),true,"dragging must not lose the photograph");
  await page.locator(".viewer-frame").dblclick();
  await page.waitForFunction(()=>new DOMMatrix(getComputedStyle(document.querySelector(".viewer-canvas img")).transform).a===1);
  assert.equal(await page.locator(".viewer-tools span").innerText(),"100%","double-click reset must update all zoom controls");
  await page.getByRole("button",{name:"放大"}).click();
  await page.getByRole("button",{name:"还原"}).click();
  await page.waitForFunction(()=>document.querySelector(".viewer-tools span").textContent==="100%");
  await page.keyboard.press("Escape");assert.equal(await page.getByRole("dialog").count(),0);
  assert.equal(await page.getByRole("button",{name:"查看原图"}).evaluate(el=>el===document.activeElement),true,"viewer must return focus to its opener");
  await page.getByRole("button",{name:"关闭作品"}).click();await page.waitForURL(/#chapter-2$/);await settle(page);
  await page.getByRole("button",{name:"播放音乐"}).click();
  await page.waitForFunction(t=>document.querySelector("audio").currentTime>t,paused);
  await page.close();
  for(const [width,height] of [[390,844],[360,640]]){
    const mobile=await browser.newPage({viewport:{width,height},hasTouch:true,isMobile:true,deviceScaleFactor:1});
    mobile.on("pageerror",e=>errors.push(e.message));
    await mobile.goto(`${url}#chapter-2`);
    await mobile.waitForFunction(()=>document.querySelector(".landing").dataset.chapter==="1");
    await mobile.getByRole("button",{name:"探索作品",exact:true}).tap();
    await mobile.waitForURL(/#signal$/);await settle(mobile);
    await mobile.waitForSelector("[data-printed]");
    await mobile.waitForFunction(()=>document.querySelector("audio").currentTime>.1);
    await mobile.getByRole("button",{name:"暂停音乐"}).tap();
    const volume=mobile.getByRole("slider",{name:"音乐音量"});
    await volume.focus();await mobile.keyboard.press("Home");await mobile.keyboard.press("ArrowRight");
    assert.equal(await mobile.evaluate(()=>document.querySelector("audio").volume),.01);
    assert.equal(await mobile.evaluate(()=>{
      const volume=document.querySelector(".sound-volume").getBoundingClientRect();
      const progress=document.querySelector('[aria-label="观看进度"]').getBoundingClientRect();
      return volume.right<=progress.left||volume.left>=progress.right||volume.bottom<=progress.top||volume.top>=progress.bottom;
    }),true,"volume must not cover the progress control");
    const slider=await mobile.getByRole("slider",{name:"观看进度"}).boundingBox();
    const session=await mobile.context().newCDPSession(mobile);
    const drag=async(from,to)=>{
      await session.send("Input.dispatchTouchEvent",{type:"touchStart",touchPoints:[from]});
      for(let i=1;i<=8;i++)await session.send("Input.dispatchTouchEvent",{type:"touchMove",touchPoints:[{x:from.x+(to.x-from.x)*i/8,y:from.y+(to.y-from.y)*i/8}]});
      await session.send("Input.dispatchTouchEvent",{type:"touchEnd",touchPoints:[]});
    };
    await drag({x:slider.x+5,y:slider.y+slider.height/2},{x:slider.x+slider.width-5,y:slider.y+slider.height/2});
    await mobile.waitForFunction(()=>document.querySelector("[data-material-stage]").dataset.phase==="2");
    const scroll=await mobile.evaluate(()=>scrollY);
    await mobile.getByRole("button",{name:"查看原图"}).tap();
    await mobile.getByRole("dialog",{name:"作品原图"}).waitFor();
    await session.send("Input.dispatchTouchEvent",{type:"touchStart",touchPoints:[{x:width/2-32,y:height/2},{x:width/2+32,y:height/2}]});
    for(const distance of [42,52,65,80])await session.send("Input.dispatchTouchEvent",{type:"touchMove",touchPoints:[{x:width/2-distance,y:height/2},{x:width/2+distance,y:height/2}]});
    await session.send("Input.dispatchTouchEvent",{type:"touchEnd",touchPoints:[]});
    await mobile.waitForFunction(()=>document.querySelector(".detail-viewer").dataset.zoomed==="true");
    await drag({x:width/2,y:height/2},{x:width-12,y:height/2+70});
    await mobile.screenshot({path:resolve(proof,`mobile-${width}-viewer.png`)});
    await mobile.getByRole("button",{name:"关闭原图"}).tap();
    assert.ok(Math.abs(await mobile.evaluate(()=>scrollY)-scroll)<2,"closing original must preserve the exact scroll position");
    await mobile.getByRole("button",{name:"I · 原作摄影"}).tap();
    await mobile.waitForFunction(()=>scrollY<5);
    await mobile.screenshot({path:resolve(proof,`mobile-${width}-controls.png`)});
    assert.equal(await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
    await mobile.close();
  }
  assert.deepEqual(errors,[]);
  console.log("Brand, reduced copy, continuous MP3, pause/volume, desktop zoom, mobile scrubbing/pinch/pan, layout and scroll restoration passed.");
}finally{await browser.close();}
